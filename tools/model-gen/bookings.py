def prisma_models():
    out = [BEGIN, '']
    for n, vs in ENUMS.items(): out += ['enum %s {' % n] + ['  ' + v for v in vs] + ['}', '']
    back = {}  # target model -> list of lines
    for m in MODELS:
        lines = []
        for f in m['F']:
            t = f['pt'] + ('?' if f['opt'] else '')
            attrs = []
            if f['name'] == 'id': attrs += ['@id(map: "%s_pkey")' % m['table'], '@default(dbgenerated("gen_random_uuid()"))']
            if f['pat']: attrs.append(f['pat'])
            if f['name'] != 'id' and f['d'] is not None: attrs.append(prisma_default(f).strip())
            if f['name'] == 'updatedAt': attrs.append('@updatedAt')
            if f['col'] != f['name']: attrs.append('@map("%s")' % f['col'])
            lines.append((f['name'], t, ' '.join(a for a in attrs if a)))
        rel = [('supplier', 'Supplier', '"%s_supplier"' % m['name'], '[supplierId]', '[id]', 'Restrict', '%s_supplier_id_fkey' % m['table'], False, 'supplierId')]
        back.setdefault('Supplier', []).append('  %s %s[] @relation("%s_supplier")%s' % (lower1(m['name']) + 's', m['name'], m['name'], BK))
        for fld, tgt, od in m['fks']:
            opt = next(f for f in m['F'] if f['name'] == fld)['opt']
            rname = fld[:-2] if fld.endswith('Id') else fld
            rel.append((rname, tgt, '"%s_%s"' % (m['name'], rname), '[supplierId, %s]' % fld, '[supplierId, id]', od, trunc('%s_supplier_id_%s_fkey' % (m['table'], snake(fld))), opt, fld))
            back.setdefault(tgt, []).append('  %s %s[] @relation("%s_%s")%s' % (lower1(m['name']) + 's' + ('' if sum(1 for x in m['fks'] if x[1] == tgt) == 1 else rname[0].upper() + rname[1:]), m['name'], m['name'], rname, BK))
        for f in m['F']:
            if f['name'] == 'currencyCode':
                rel.append(('currency', 'Currency', '"%s_currency"' % m['name'], '[currencyCode]', '[code]', 'Restrict', '%s_currency_code_fkey' % m['table'], False, 'currencyCode'))
                back.setdefault('Currency', []).append('  %s %s[] @relation("%s_currency")%s' % (lower1(m['name']) + 's', m['name'], m['name'], BK))
        # self relation (Payment.refundOf) needs an opposite field on the same model
        body = ['model %s {' % m['name']]
        w = max(len(x[0]) for x in lines)
        for n, t, a in lines: body.append('  %s %s %s' % (n.ljust(w), t.ljust(14), a))
        for rname, tgt, rn, fields, refs, od, mapn, opt, fld in rel:
            body.append('  %s %s%s @relation(%s, fields: %s, references: %s, onDelete: %s, onUpdate: Cascade, map: "%s")' % (rname, tgt, '?' if opt else '', rn, fields, refs, od, mapn))
        # back-relations from other booking models that point at this one
        for o in MODELS:
            for fld, tgt, od in o['fks']:
                if tgt == m['name']:
                    rname = fld[:-2]
                    nm = lower1(o['name']) + 's' + ('' if sum(1 for x in o['fks'] if x[1] == tgt) == 1 else rname[0].upper() + rname[1:])
                    body.append('  %s %s[] @relation("%s_%s")' % (nm, o['name'], o['name'], rname))
        for u in m['uniques']: body.append('  @@unique([%s], map: "%s")' % (', '.join(u), trunc('%s_%s_key' % (m['table'], '_'.join(cols(m, u))))))
        for i in m['indexes']: body.append('  @@index([%s], map: "%s")' % (', '.join(i), trunc('%s_%s_idx' % (m['table'], '_'.join(cols(m, i))))))
        body += ['  @@map("%s")' % m['table'], '}', '']
        out += body
    out.append(END)
    # backrelations only for non-booking targets (booking-to-booking were written inline)
    external = {k: v for k, v in back.items() if k not in BY_NAME}
    return '\n'.join(out) + '\n', external

def patch_schema():
    s = open(SCHEMA).read()
    s = re.sub(r'\n?' + re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n?', '\n', s, flags=re.S)
    s = '\n'.join(l for l in s.split('\n') if not l.endswith(BK))
    s = re.sub(r'\n  @@unique\(\[supplierId, id\], map: "[a-z_]+_supplier_id_id_key"\)' + re.escape(BK), '', s)
    block, external = prisma_models()
    # supplier_id + id unique keys for master tables that did not have one
    for t in NEED_SUPPLIER_ID_UNIQUE:
        mm = re.search(r'model %s \{.*?\n\}' % t, s, re.S)
        if '@@unique([supplierId, id]' not in mm.group(0):
            new = mm.group(0).replace('\n  @@map(', '\n  @@unique([supplierId, id], map: "%s_supplier_id_id_key")%s\n  @@map(' % (TARGET[t], BK), 1)
            s = s.replace(mm.group(0), new)
    # a booking Customer can also point at a country; keep countries out of the FK set on purpose (free text code, validated by the API)
    for tgt, lines in external.items():
        mm = re.search(r'model %s \{.*?\n\}' % tgt, s, re.S)
        seen, uniq = set(), []
        for l in lines:
            if l not in seen: seen.add(l); uniq.append(l)
        txt = mm.group(0)
        idx = txt.find('\n  @@')
        add = '\n' + '\n'.join(uniq)
        new = (txt[:idx] + add + txt[idx:]) if idx > 0 else txt[:-2] + add + '\n}'
        s = s.replace(txt, new)
    s = s.rstrip('\n') + '\n\n' + block
    open(SCHEMA, 'w').write(s)

if __name__ == '__main__':
    write_migrations(); patch_schema()
