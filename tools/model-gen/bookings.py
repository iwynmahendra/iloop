def parse(fs):
    m = re.match(r"^(\w+)\s+(e:\w+|[a-z]+(?:\([\d,]+\))?)(\?)?(?:\s*=\s*(.+))?$", fs)
    if not m: raise Exception('bad field ' + fs)
    name, t, opt, d = m.groups()
    f = dict(name=name, col=snake(name), opt=bool(opt), d=d, enum=None)
    k = re.match(r'([a-z]+)(?:\(([\d,]+)\))?', t); kk, arg = k.group(1), k.group(2)
    if t.startswith('e:'): f.update(pt='String' if False else t[2:], pat='', sql='"%s"' % t[2:], enum=t[2:])
    elif kk == 's': f.update(pt='String', pat=('@db.VarChar(%s)' % arg) if arg else '', sql=('VARCHAR(%s)' % arg) if arg else 'TEXT')
    elif kk == 'i': f.update(pt='Int', pat='', sql='INTEGER')
    elif kk == 'si': f.update(pt='Int', pat='@db.SmallInt', sql='SMALLINT')
    elif kk == 'd': f.update(pt='Decimal', pat='@db.Decimal(%s)' % arg, sql='DECIMAL(%s)' % arg)
    elif kk == 'b': f.update(pt='Boolean', pat='', sql='BOOLEAN')
    elif kk == 'dt': f.update(pt='DateTime', pat='@db.Timestamptz(6)', sql='TIMESTAMPTZ(6)')
    elif kk == 'dd': f.update(pt='DateTime', pat='@db.Date', sql='DATE')
    elif kk == 'j': f.update(pt='Json', pat='', sql='JSONB')
    elif kk == 'u': f.update(pt='String', pat='@db.Uuid', sql='UUID')
    elif kk == 'ch': f.update(pt='String', pat='@db.Char(%s)' % arg, sql='CHAR(%s)' % arg)
    elif kk == 't': f.update(pt='String', pat='@db.VarChar(5)', sql='VARCHAR(5)')
    else: raise Exception('type ' + t)
    return f

def sql_default(f):
    d = f['d']
    if d is None: return ''
    if d == 'now': return ' DEFAULT CURRENT_TIMESTAMP'
    if f['enum']: return " DEFAULT '%s'" % d
    if f['sql'] == 'JSONB': return " DEFAULT '%s'" % d
    return ' DEFAULT %s' % d

def prisma_default(f):
    d = f['d']
    if d is None: return ''
    if d == 'now': return ' @default(now())'
    if f['enum']: return ' @default(%s)' % d
    if f['sql'] == 'JSONB': return ' @default("%s")' % d
    if f['pt'] == 'String': return ' @default(%s)' % d.replace("'", '"')
    return ' @default(%s)' % d

